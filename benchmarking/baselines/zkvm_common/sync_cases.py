"""Regenerate the per-case glue from the case folders.

A case takes part in the Rust zkVM baselines when its folder
`benchmarking/datasets/ds1000/<case>/` has a `zkvm.rs`, and in the Cairo
baseline when it has a `main.cairo`. This script writes

* `zkvm_common/ds1000/src/cases.rs`: the case list of the kernels crate;
* `sp1/guest/src/bin/<case>.rs` and `risc0/methods/guest/src/bin/<case>.rs`:
  one guest binary per case (stale ones are removed);
* `cairo/Scarb.toml`'s executable targets and `cairo/src/cases/<case>.cairo`
  symlinks.

Run it after adding or removing a case: `python3 sync_cases.py`.
"""

from __future__ import annotations

import os
from pathlib import Path

BASELINES = Path(__file__).resolve().parents[1]
DATASET = BASELINES.parent / "datasets" / "ds1000"
HEADER = "Generated by `zkvm_common/sync_cases.py`; do not edit."


def cases_with(filename: str) -> list[str]:
    return sorted(d.name for d in DATASET.iterdir() if (d / filename).is_file())


def write_if_changed(path: Path, text: str) -> None:
    if not path.exists() or path.read_text() != text:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)


def sync_bins(bin_dir: Path, cases: list[str], body: str) -> None:
    bin_dir.mkdir(parents=True, exist_ok=True)
    for stale in bin_dir.glob("*.rs"):
        if stale.stem not in cases:
            stale.unlink()
    for case in cases:
        write_if_changed(bin_dir / f"{case}.rs", f"// {HEADER}\n" + body.format(case=case))


def sync_rust(cases: list[str]) -> None:
    lines = [f"// {HEADER}", "cases! {"]
    lines += [f'    {c} => "../../../../datasets/ds1000/{c}/zkvm.rs",' for c in cases]
    lines.append("}")
    write_if_changed(BASELINES / "zkvm_common" / "ds1000" / "src" / "cases.rs", "\n".join(lines) + "\n")
    sync_bins(BASELINES / "sp1" / "guest" / "src" / "bin", cases,
              "#![no_main]\nsp1_ds1000_guest::guest!({case});\n")
    sync_bins(BASELINES / "risc0" / "methods" / "guest" / "src" / "bin", cases,
              "risc0_ds1000_guest::guest!({case});\n")


def sync_cairo(cases: list[str]) -> None:
    cairo = BASELINES / "cairo"
    if not (cairo / "Scarb.toml.in").exists():
        return
    links = cairo / "src" / "cases"
    links.mkdir(parents=True, exist_ok=True)
    for stale in links.glob("*.cairo"):
        if stale.stem not in cases:
            stale.unlink()
    for case in cases:
        link = links / f"{case}.cairo"
        target = os.path.relpath(DATASET / case / "main.cairo", links)
        if not link.is_symlink() or os.readlink(link) != target:
            link.unlink(missing_ok=True)
            link.symlink_to(target)
    mods = [f"// {HEADER}"] + [f"pub mod {c};" for c in cases]
    write_if_changed(cairo / "src" / "cases.cairo", "\n".join(mods) + "\n")
    targets = "".join(
        f'\n[[target.executable]]\nname = "{c}"\nfunction = "ds1000_cairo::cases::{c}::main"\n' for c in cases
    )
    template = (cairo / "Scarb.toml.in").read_text()
    write_if_changed(cairo / "Scarb.toml", template.replace("# @EXECUTABLES@", f"# {HEADER}{targets}"))


if __name__ == "__main__":
    sync_rust(cases_with("zkvm.rs"))
    sync_cairo(cases_with("main.cairo"))
