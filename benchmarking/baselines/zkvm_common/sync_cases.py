"""Regenerate the per-case glue from the case folders.

A case takes part in the Rust zkVM baselines when its folder has a `zkvm.rs`,
and in the Cairo baseline when it has a `main.cairo`. Case folders are
`benchmarking/datasets/ds1000/<case>/` and the calibration programs in
`zkvm_common/calibration/<name>/`. This script writes

* `zkvm_common/ds1000/src/cases.rs`: the case list of the kernels crate;
* `sp1/guest/src/bin/<case>.rs` and `risc0/methods/guest/src/bin/<case>.rs`:
  one guest binary per case (stale ones are removed);
* `cairo/Scarb.toml` (from `Scarb.toml.in`) with one executable target per
  case, `cairo/src/cases.cairo`, and `cairo/src/cases/<case>.cairo` symlinks.

Run it after adding or removing a case: `python3 sync_cases.py`.
"""

from __future__ import annotations

import os
from pathlib import Path

BASELINES = Path(__file__).resolve().parents[1]
CASE_ROOTS = [BASELINES.parent / "datasets" / "ds1000", BASELINES / "zkvm_common" / "calibration"]
HEADER = "Generated by `zkvm_common/sync_cases.py`; do not edit."


def case_dirs_with(filename: str) -> dict[str, Path]:
    found = {}
    for root in CASE_ROOTS:
        for d in sorted(root.iterdir()):
            if (d / filename).is_file():
                found[d.name] = d
    return found


def write_if_changed(path: Path, text: str) -> None:
    if not path.exists() or path.read_text() != text:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)


def sync_bins(bin_dir: Path, cases: list[str], body: str) -> None:
    bin_dir.mkdir(parents=True, exist_ok=True)
    for stale in bin_dir.glob("*.rs"):
        if stale.stem not in cases:
            stale.unlink()
    for case in cases:
        write_if_changed(bin_dir / f"{case}.rs", f"// {HEADER}\n" + body.format(case=case))


def sync_rust(cases: dict[str, Path]) -> None:
    crate_src = BASELINES / "zkvm_common" / "ds1000" / "src"
    lines = [f"// {HEADER}", "cases! {"]
    lines += [f'    {name} => "{os.path.relpath(d / "zkvm.rs", crate_src)}",' for name, d in cases.items()]
    lines.append("}")
    write_if_changed(crate_src / "cases.rs", "\n".join(lines) + "\n")
    names = list(cases)
    sync_bins(BASELINES / "sp1" / "guest" / "src" / "bin", names,
              "#![no_main]\nsp1_ds1000_guest::guest!({case});\n")
    sync_bins(BASELINES / "risc0" / "methods" / "guest" / "src" / "bin", names,
              "risc0_ds1000_guest::guest!({case});\n")


def sync_cairo(cases: dict[str, Path]) -> None:
    cairo = BASELINES / "cairo"
    links = cairo / "src" / "cases"
    links.mkdir(parents=True, exist_ok=True)
    for stale in links.glob("*.cairo"):
        if stale.stem not in cases:
            stale.unlink()
    for name, d in cases.items():
        link = links / f"{name}.cairo"
        target = os.path.relpath(d / "main.cairo", links)
        if not link.is_symlink() or os.readlink(link) != target:
            link.unlink(missing_ok=True)
            link.symlink_to(target)
    mods = [f"// {HEADER}"] + [f"pub mod {name};" for name in cases]
    write_if_changed(cairo / "src" / "cases.cairo", "\n".join(mods) + "\n")
    targets = "".join(
        f'\n[[target.executable]]\nname = "{name}"\nfunction = "ds1000_cairo::cases::{name}::main"\n'
        for name in cases
    )
    template = (cairo / "Scarb.toml.in").read_text()
    write_if_changed(cairo / "Scarb.toml", template.replace("# @EXECUTABLES@", f"# {HEADER}{targets}"))


if __name__ == "__main__":
    sync_rust(case_dirs_with("zkvm.rs"))
    sync_cairo(case_dirs_with("main.cairo"))
