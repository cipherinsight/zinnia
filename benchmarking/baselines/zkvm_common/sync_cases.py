"""Regenerate the per-case glue from the case folders.

Programs:
* fixed-shape programs: `datasets/ds1000/<case>/zkvm.rs` and the calibration
  programs `zkvm_common/calibration/<name>/zkvm.rs` (one case each);
* shape-generic programs: `datasets/{npbench,pythran}/<program>/zkvm.rs`, one
  case `<program>/<function>` per top-level `pub mod <function>` (an entry
  function) in the file.

A parameter a case never reads is declared by a line
`// unused parameters: a, b` in its program (for a shape-generic program,
inside the entry function's module).

The Cairo baseline covers the fixed-shape programs that have a `main.cairo`.

This script writes
* `zkvm_common/kernels/src/cases.rs`: the program and case lists of the
  kernels crate;
* `sp1/guest/src/bin/<case>.rs` and `risc0/methods/guest/src/bin/<case>.rs`:
  one guest binary per case (`/` in a case name becomes `__`; stale binaries
  are removed);
* `cairo/Scarb.toml` (from `Scarb.toml.in`) with one executable target per
  Cairo case, `cairo/src/cases.cairo`, and `cairo/src/cases/<case>.cairo`
  symlinks.

Run it after adding or removing a case: `python3 sync_cases.py`.
"""

from __future__ import annotations

import json
import os
import re
from dataclasses import dataclass, field
from pathlib import Path

BASELINES = Path(__file__).resolve().parents[1]
DATASETS = BASELINES.parent / "datasets"
FIXED_ROOTS = [DATASETS / "ds1000", BASELINES / "zkvm_common" / "calibration"]
SHAPED_ROOTS = [DATASETS / "npbench", DATASETS / "pythran"]
CRATE_SRC = BASELINES / "zkvm_common" / "kernels" / "src"
HEADER = "Generated by `zkvm_common/sync_cases.py`; do not edit."
UNUSED = re.compile(r"^\s*//\s*unused parameters:\s*(.+?)\s*$", re.M)
ENTRY = re.compile(r"^pub mod (\w+)\s*\{", re.M)


@dataclass
class Case:
    name: str                 # case key: module name, or "<program>/<function>"
    module_path: str          # Rust path of the module with `main` and `Output`
    shaped: bool
    unused: list[str] = field(default_factory=list)

    @property
    def binary(self) -> str:
        return self.name.replace("/", "__")


def unused_params(text: str) -> list[str]:
    match = UNUSED.search(text)
    return [name.strip() for name in match.group(1).split(",")] if match else []


def program_dirs(roots: list[Path], filename: str) -> dict[str, Path]:
    found = {}
    for root in roots:
        if root.is_dir():
            for d in sorted(root.iterdir()):
                if (d / filename).is_file():
                    found[d.name] = d
    return found


def rust_cases() -> tuple[dict[str, Path], list[Case]]:
    modules, cases = {}, []
    for name, d in program_dirs(FIXED_ROOTS, "zkvm.rs").items():
        modules[name] = d
        cases.append(Case(name, name, shaped=False, unused=unused_params((d / "zkvm.rs").read_text())))
    for name, d in program_dirs(SHAPED_ROOTS, "zkvm.rs").items():
        modules[name] = d
        text = (d / "zkvm.rs").read_text()
        entries = list(ENTRY.finditer(text))
        if not entries:
            raise SystemExit(f"{d}/zkvm.rs declares no entry function (`pub mod <function> {{`)")
        for i, entry in enumerate(entries):
            body = text[entry.end(): entries[i + 1].start() if i + 1 < len(entries) else len(text)]
            function = entry.group(1)
            cases.append(Case(f"{name}/{function}", f"{name}::{function}", shaped=True, unused=unused_params(body)))
    return modules, cases


def write_if_changed(path: Path, text: str) -> None:
    if not path.exists() or path.read_text() != text:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)


def sync_bins(bin_dir: Path, cases: list[Case], crate: str) -> None:
    bin_dir.mkdir(parents=True, exist_ok=True)
    wanted = {case.binary for case in cases}
    for stale in bin_dir.glob("*.rs"):
        if stale.stem not in wanted:
            stale.unlink()
    for case in cases:
        kind = "shaped" if case.shaped else "fixed"
        body = f"// {HEADER}\n" + ("#![no_main]\n" if crate.startswith("sp1") else "")
        body += f"{crate}::guest!({kind} {case.module_path});\n"
        write_if_changed(bin_dir / f"{case.binary}.rs", body)


def unused_suffix(case: Case) -> str:
    return f" [unused {', '.join(json.dumps(u) for u in case.unused)}]" if case.unused else ""


def sync_rust() -> None:
    modules, cases = rust_cases()
    lines = [f"// {HEADER}", "programs! {", "    modules {"]
    lines += [f'        {name} => "{os.path.relpath(d / "zkvm.rs", CRATE_SRC)}";' for name, d in modules.items()]
    lines += ["    }", "    fixed {"]
    lines += [f"        {c.name}{unused_suffix(c)};" for c in cases if not c.shaped]
    lines += ["    }", "    shaped {"]
    lines += [f'        "{c.name}" => {c.module_path}{unused_suffix(c)};' for c in cases if c.shaped]
    lines += ["    }", "}"]
    write_if_changed(CRATE_SRC / "cases.rs", "\n".join(lines) + "\n")
    sync_bins(BASELINES / "sp1" / "guest" / "src" / "bin", cases, "sp1_kernels_guest")
    sync_bins(BASELINES / "risc0" / "methods" / "guest" / "src" / "bin", cases, "risc0_kernels_guest")


def sync_cairo() -> None:
    cases = program_dirs(FIXED_ROOTS, "main.cairo")
    cairo = BASELINES / "cairo"
    links = cairo / "src" / "cases"
    links.mkdir(parents=True, exist_ok=True)
    for stale in links.glob("*.cairo"):
        if stale.stem not in cases:
            stale.unlink()
    for name, d in cases.items():
        link = links / f"{name}.cairo"
        target = os.path.relpath(d / "main.cairo", links)
        if not link.is_symlink() or os.readlink(link) != target:
            link.unlink(missing_ok=True)
            link.symlink_to(target)
    mods = [f"// {HEADER}"] + [f"pub mod {name};" for name in cases]
    write_if_changed(cairo / "src" / "cases.cairo", "\n".join(mods) + "\n")
    targets = "".join(
        f'\n[[target.executable]]\nname = "{name}"\nfunction = "ds1000_cairo::cases::{name}::main"\n'
        for name in cases
    )
    template = (cairo / "Scarb.toml.in").read_text()
    write_if_changed(cairo / "Scarb.toml", template.replace("# @EXECUTABLES@", f"# {HEADER}{targets}"))


if __name__ == "__main__":
    sync_rust()
    sync_cairo()
