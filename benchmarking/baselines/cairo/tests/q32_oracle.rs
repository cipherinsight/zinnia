//! Generates Cairo assertions from the unchanged Rust Q32 reference.
use q32::{Q32, C32};
fn q(n: i64) -> Q32 { Q32::from_bits(n) }
fn unary(name: &str, values: &[i64], f: fn(Q32)->Q32) {
    for (chunk, xs) in values.chunks(32).enumerate() {
        println!("#[test]\nfn {name}_{chunk}() {{");
        for &x in xs { println!("assert!(Q32 {{ bits: {x} }}.{name}().bits == {});", f(q(x)).to_bits()); }
        println!("}}");
    }
}
fn main() {
    println!("// Generated by tests/generate_q32_vectors.py from zkvm_common/q32; do not edit.\nuse super::{{Q32, Q32Trait, C32, C32Trait}};");
    let mut grid: Vec<i64> = (-192..=136).map(|i| i * (1<<32) / 7).collect();
    grid.extend([-100<<32, -45<<32, -1, 0, 1, 2977044472/2-1, 2977044472/2, 2977044472/2+1, 21<<32]);
    unary("exp", &grid, Q32::exp);
    let mut positive: Vec<i64> = (0..63).flat_map(|k| [(1i64<<k).saturating_sub(1).max(1), 1i64<<k, (1i64<<k)+1]).collect();
    positive.extend([i64::MAX, 1, 3, 4294967295]);
    unary("ln", &positive, Q32::ln);
    grid.extend([-1000000<<32, 1000000<<32]);
    unary("tanh", &grid, Q32::tanh);
    grid.extend([i64::MIN+1, i64::MAX, -(1<<32)-1, -(1<<32), (1<<32)-1, 1<<32, (1<<32)+1]);
    unary("atan", &grid, Q32::atan);
    unary("floor", &grid, Q32::floor);
    for (i, &y) in [-123456789012i64,-4294967296,-1,0,1,4294967296,123456789012].iter().enumerate() {
        println!("#[test]\nfn atan2_{i}() {{");
        for x in [-123456789012i64,-4294967296,-1,0,1,4294967296,123456789012] {
            println!("assert!(Q32 {{ bits: {y} }}.atan2(Q32 {{ bits: {x} }}).bits == {});",q(y).atan2(q(x)).to_bits());
        }
        println!("}}");
    }
    for i in -10..=10i64 {
        let x=i*(1<<32)/7;
        println!("#[test]\nfn powers_{}() {{",i+10);
        for n in [0,1,2,3,4,7,10] { println!("assert!(Q32 {{ bits: {x} }}.powi({n}).bits == {});",q(x).powi(n).to_bits()); }
        if x>0 {
            for y in [-2<<32,-1,0,1,1<<31,1<<32,3<<32] {
                println!("assert!(Q32 {{ bits: {x} }}.powf(Q32 {{ bits: {y} }}).bits == {});",q(x).powf(q(y)).to_bits());
            }
        }
        println!("}}");
    }
    for i in -20..=20i64 {
        let a=C32::new(q(i*(1<<32)/7),q((i+1)*(1<<32)/9));
        let b=C32::new(q((i-1)*(1<<32)/11),q((i+3)*(1<<32)/13));
        println!("#[test]\nfn complex_{}() {{",i+20);
        println!("let a = C32 {{ re: Q32 {{ bits: {} }}, im: Q32 {{ bits: {} }} }};", a.re.to_bits(),a.im.to_bits());
        println!("let b = C32 {{ re: Q32 {{ bits: {} }}, im: Q32 {{ bits: {} }} }};", b.re.to_bits(),b.im.to_bits());
        for (expr,v) in [("a + b",a+b),("a - b",a-b),("-a",-a),("a * b",a*b),("a / b",a/b),("a.conj()",a.conj()),("a.exp()",a.exp()),("a.scale(b.re)",a*b.re)] {
            println!("let v = {expr}; assert!(v.re.bits == {} && v.im.bits == {});",v.re.to_bits(),v.im.to_bits());
        }
        for (expr,v) in [("a.abs()",a.abs()),("a.norm_sqr()",a.norm_sqr())] { println!("assert!({expr}.bits == {});",v.to_bits()); }
        println!("}}");
    }
}
