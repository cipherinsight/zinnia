"""Writes a Noir `Prover.toml` from a case's `fixture.json`.

The values are laid out by the compiled program's ABI (`target/<pkg>.json`),
matched to fixture parameters by name, so a baseline may declare a parameter
flat (`[Field; 48]`), nested (`[[Field; 6]; 8]`), as a native integer type or
as a boolean; the row-major order of the fixture is kept.

Encoding of each leaf:
- a `float` fixture value becomes its Q32 integer `round(v * 2^32)`, Zinnia's
  quantizer (`src/prove/field.rs::quantize`);
- an `int` value is written as is, a `bool` as `true`/`false` (boolean ABI
  type) or `1`/`0` (field or integer ABI type).

Usage (writes `<case>/Prover.toml` for input B, the input every timed proof uses):
    python -m hw_check.prover_toml <case_dir> [--fixture F] [--input B] [--out PATH]
"""
from __future__ import annotations

import json
import math
from pathlib import Path

BN254_P = 0x30644E72E131A029B85045B68181585D2833E84879B9709143E1F593F0000001
SCALE = 1 << 32


def quantize(v: float) -> int:
    """`(v * 2^32).round() as i128` in Rust: half-way cases away from zero.

    Doubles of magnitude 2^52 or more are already integers (and adding 0.5
    to them would round), so they are taken as they are."""
    x = abs(v * SCALE)
    n = int(x) if x >= 2.0**52 else math.floor(x + 0.5)
    return -n if v < 0 else n


def _leaf_count(abi_type: dict) -> int:
    if abi_type["kind"] == "array":
        return abi_type["length"] * _leaf_count(abi_type["type"])
    if abi_type["kind"] in ("field", "integer", "boolean"):
        return 1
    raise ValueError(f"unsupported ABI type {abi_type}")


def _flatten(v) -> list:
    if isinstance(v, list):
        return [y for x in v for y in _flatten(x)]
    return [v]


def _toml_int(n: int) -> str:
    if -(1 << 63) <= n < (1 << 63):
        return str(n)
    return f'"{hex(n % BN254_P)}"'


def _encode_leaf(value, dtype: str, abi_type: dict) -> str:
    if dtype == "float":
        n = quantize(float(value))
    elif dtype == "bool":
        n = int(bool(value))
    else:
        n = int(value)
    kind = abi_type["kind"]
    if kind == "boolean":
        if n not in (0, 1):
            raise ValueError(f"{value!r} is not a boolean")
        return "true" if n else "false"
    if kind == "integer":
        width = abi_type["width"]
        lo, hi = (-(1 << (width - 1)), 1 << (width - 1)) if abi_type["sign"] == "signed" else (0, 1 << width)
        if not lo <= n < hi:
            raise ValueError(f"{value!r} (encoded {n}) does not fit {abi_type}")
    return _toml_int(n)


def _render(leaves: list[str], abi_type: dict) -> str:
    if abi_type["kind"] != "array":
        return leaves[0]
    inner = abi_type["type"]
    step = _leaf_count(inner)
    parts = [_render(leaves[i * step:(i + 1) * step], inner) for i in range(abi_type["length"])]
    return "[" + ", ".join(parts) + "]"


def render_prover_toml(abi: dict, fixture: dict, input_name: str,
                       tamper: tuple[str, int] | None = None) -> str:
    """`tamper = (name, index)` adds 2^64 to that leaf's field value, putting it
    outside every input domain (the input-domain tamper test)."""
    params = {p["name"]: p for p in fixture["parameters"]}
    values = fixture["inputs"][input_name]
    lines = [f"# Generated by hw_check.prover_toml from fixture.json, input {input_name}."]
    for abi_param in abi["parameters"]:
        name = abi_param["name"]
        if name not in params:
            raise KeyError(f"main.nr parameter {name!r} is not a kernel parameter")
        flat = _flatten(values[name])
        abi_type = abi_param["type"]
        if len(flat) != _leaf_count(abi_type):
            raise ValueError(f"{name}: fixture has {len(flat)} values, main.nr expects {_leaf_count(abi_type)}")
        leaves = [_encode_leaf(v, params[name]["dtype"], _first_leaf_type(abi_type)) for v in flat]
        if tamper is not None and tamper[0] == name:
            if _first_leaf_type(abi_type)["kind"] != "field":
                raise ValueError(f"{name}: only Field inputs can be tampered")
            leaves[tamper[1]] = _toml_int(int(leaves[tamper[1]].strip('"'), 0) + (1 << 64))
        lines.append(f"{name} = {_render(leaves, abi_type)}")
    missing = set(params) - {p["name"] for p in abi["parameters"]}
    if missing:
        lines.append(f"# kernel parameters not used by main.nr: {sorted(missing)}")
    return "\n".join(lines) + "\n"


def _first_leaf_type(abi_type: dict) -> dict:
    while abi_type["kind"] == "array":
        abi_type = abi_type["type"]
    return abi_type


def main() -> None:
    import argparse
    import tempfile

    from .noir_driver import compile_package, stage_package

    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("case_dirs", type=Path, nargs="+")
    ap.add_argument("--fixture", type=Path, help="defaults to <case>/fixture.json")
    ap.add_argument("--input", default="B")
    ap.add_argument("--out", type=Path, help="defaults to <case>/Prover.toml")
    a = ap.parse_args()
    for case_dir in a.case_dirs:
        fixture = json.loads((a.fixture or case_dir / "fixture.json").read_text())
        with tempfile.TemporaryDirectory() as tmp:
            pkg = stage_package(case_dir, Path(tmp))
            abi = compile_package(pkg)["abi"]
        out = a.out or case_dir / "Prover.toml"
        out.write_text(render_prover_toml(abi, fixture, a.input))
        print(f"wrote {out}")


if __name__ == "__main__":
    main()
