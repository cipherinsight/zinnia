//! Handwritten halo2-base baselines for the DS-1000 performance set.
//!
//! Each case's circuit lives next to its kernel, in
//! `benchmarking/datasets/ds1000/<case>/target.rs`, and is compiled into this
//! crate as module `cases::<case>` (see `build.rs`). A circuit is a function
//!
//! ```ignore
//! pub fn circuit(builder: &mut Builder, inputs: &Inputs, out: &mut Outputs) -> Result<()>
//! ```
//!
//! that loads the private inputs, computes the kernel with halo2-base and the
//! [`q32`] helpers, and hands its return value to `out`. Everything else
//! (sizing, keys, proving, verifying, output decoding) is shared and lives in
//! [`scaffold`]; the rules the circuits follow are in
//! `benchmarking/baselines/CONVENTIONS.md`.

pub mod fixture;
pub mod outputs;
pub mod params;
pub mod q32;
pub mod scaffold;

use halo2_base::gates::circuit::builder::BaseCircuitBuilder;
use halo2_base::halo2_proofs::halo2curves::bn256::Fr;

/// The circuit builder every baseline writes into.
pub type Builder = BaseCircuitBuilder<Fr>;

/// A baseline circuit.
pub type CircuitFn = fn(&mut Builder, &fixture::Inputs, &mut outputs::Outputs) -> Result<(), Error>;

/// An error reported to the caller (never a panic on a user input).
#[derive(Clone, Debug)]
pub struct Error(pub String);

impl Error {
    pub fn new(msg: impl Into<String>) -> Self {
        Error(msg.into())
    }
}

impl std::fmt::Display for Error {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(&self.0)
    }
}

impl From<String> for Error {
    fn from(s: String) -> Self {
        Error(s)
    }
}

impl From<&str> for Error {
    fn from(s: &str) -> Self {
        Error(s.to_string())
    }
}

/// What a `target.rs` imports.
pub mod prelude {
    pub use crate::fixture::Inputs;
    pub use crate::outputs::{Kind, Outputs};
    pub use crate::q32::{fe, quantize, Cell, Ctx, I64, Q32, SCALE};
    pub use crate::{Builder, Error};
    pub use halo2_base::gates::{GateInstructions, RangeInstructions};
    pub use halo2_base::halo2_proofs::arithmetic::Field;
    pub use halo2_base::halo2_proofs::halo2curves::bn256::Fr;
    pub use halo2_base::QuantumCell::{self, Constant, Existing, Witness};

    pub type Result<T> = std::result::Result<T, Error>;
}

/// The registered cases, generated by `build.rs` from the dataset folders.
pub mod cases {
    include!(concat!(env!("OUT_DIR"), "/cases.rs"));
}
