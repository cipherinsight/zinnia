//! Registers every `benchmarking/datasets/ds1000/<case>/target.rs` as module
//! `cases::<case>` and generates `cases::lookup(name)`.
//!
//! `HALO2_HW_CASES` (comma-separated case names or numbers, e.g.
//! `0300,ds1000_case0309`) restricts the build to those cases; this keeps
//! iteration builds small. Unset, every case with a `target.rs` is built.

use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::PathBuf;

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let dataset = manifest.join("../../datasets/ds1000").canonicalize().expect("dataset folder");
    println!("cargo:rerun-if-changed={}", dataset.display());
    println!("cargo:rerun-if-env-changed=HALO2_HW_CASES");

    let wanted: Option<Vec<String>> = env::var("HALO2_HW_CASES").ok().map(|s| {
        s.split(',')
            .map(str::trim)
            .filter(|c| !c.is_empty())
            .map(|c| if c.starts_with("ds1000_case") { c.to_string() } else { format!("ds1000_case{c}") })
            .collect()
    });

    let mut cases: Vec<(String, PathBuf)> = fs::read_dir(&dataset)
        .expect("read dataset folder")
        .filter_map(|e| e.ok())
        .map(|e| e.path())
        .filter_map(|dir| {
            let name = dir.file_name()?.to_str()?.to_string();
            let target = dir.join("target.rs");
            target.is_file().then_some((name, target))
        })
        .filter(|(name, _)| wanted.as_ref().map_or(true, |w| w.contains(name)))
        .collect();
    cases.sort();
    if let Some(w) = &wanted {
        for name in w {
            if !cases.iter().any(|(n, _)| n == name) {
                panic!("HALO2_HW_CASES names {name}, which has no target.rs");
            }
        }
    }

    let mut src = String::from("// @generated by build.rs\n");
    for (name, path) in &cases {
        println!("cargo:rerun-if-changed={}", path.display());
        writeln!(src, "#[path = {:?}]\npub mod {name};", path.display().to_string()).unwrap();
    }
    src.push_str("\n/// The circuit of a case, by folder name.\npub fn lookup(name: &str) -> Option<crate::CircuitFn> {\n    match name {\n");
    for (name, _) in &cases {
        writeln!(src, "        {name:?} => Some({name}::circuit),").unwrap();
    }
    src.push_str("        _ => None,\n    }\n}\n\n/// Every case compiled into this build.\npub const ALL: &[&str] = &[\n");
    for (name, _) in &cases {
        writeln!(src, "    {name:?},").unwrap();
    }
    src.push_str("];\n");
    fs::write(PathBuf::from(env::var("OUT_DIR").unwrap()).join("cases.rs"), src).unwrap();
}
