//! Registers every handwritten circuit as a module of `cases` and generates
//! `cases::lookup(name)`:
//!
//! - DS-1000: `benchmarking/datasets/ds1000/<case>/target.rs` is module
//!   `<case>` (`ds1000_case0309`);
//! - NPBench and Pythran: `benchmarking/datasets/{npbench,pythran}/<program>/target.<function>.rs`
//!   is module `<program>__<function>`, the entry's id in the case set
//!   (`pythran_lu__factorMatrix0`). One program folder holds one circuit per
//!   entry function.
//!
//! `HALO2_HW_CASES` (comma-separated) restricts the build to the named cases;
//! this keeps iteration builds small. A bare number names a DS-1000 case
//! (`0300` is `ds1000_case0300`), anything else is a case id as is. Unset,
//! every circuit is built.
//!
//! `HALO2_HW_NPB_SOURCE_ROOT` replaces NPBench/Pythran source discovery with
//! program folders under a materialized scaling cap (e.g. DATA/cap32). IDs
//! remain `<program>__<function>`; use a separate target directory per cap.

use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

/// The dataset folders whose programs have one circuit per entry function.
const SHAPE_GENERIC_DATASETS: &[&str] = &["npbench", "pythran"];

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let datasets = manifest.join("../../datasets").canonicalize().expect("datasets folder");
    println!("cargo:rerun-if-env-changed=HALO2_HW_CASES");
    println!("cargo:rerun-if-env-changed=HALO2_HW_NPB_SOURCE_ROOT");

    let wanted: Option<Vec<String>> = env::var("HALO2_HW_CASES").ok().map(|s| {
        s.split(',')
            .map(str::trim)
            .filter(|c| !c.is_empty())
            .map(|c| if c.bytes().all(|b| b.is_ascii_digit()) { format!("ds1000_case{c}") } else { c.to_string() })
            .collect()
    });

    let mut cases = ds1000_cases(&datasets.join("ds1000"));
    let source_root = env::var_os("HALO2_HW_NPB_SOURCE_ROOT").map(PathBuf::from);
    cases.extend(npb_cases(&datasets, source_root.as_deref()));
    cases.retain(|(name, _)| wanted.as_ref().map_or(true, |w| w.contains(name)));
    cases.sort();
    if let Some(w) = &wanted {
        for name in w {
            if !cases.iter().any(|(n, _)| n == name) {
                panic!("HALO2_HW_CASES names {name}, which has no target.rs");
            }
        }
    }

    let mut src = String::from("// @generated by build.rs\n");
    for (name, path) in &cases {
        println!("cargo:rerun-if-changed={}", path.display());
        // Entry functions keep their Python names (`factorMatrix0`, `CROTG`).
        writeln!(src, "#[allow(non_snake_case)]\n#[path = {:?}]\npub mod {name};", path.display().to_string()).unwrap();
    }
    src.push_str("\n/// The circuit of a case, by case id.\npub fn lookup(name: &str) -> Option<crate::CircuitFn> {\n    match name {\n");
    for (name, _) in &cases {
        writeln!(src, "        {name:?} => Some({name}::circuit),").unwrap();
    }
    src.push_str("        _ => None,\n    }\n}\n\n/// Every case compiled into this build.\npub const ALL: &[&str] = &[\n");
    for (name, _) in &cases {
        writeln!(src, "    {name:?},").unwrap();
    }
    src.push_str("];\n");
    fs::write(PathBuf::from(env::var("OUT_DIR").unwrap()).join("cases.rs"), src).unwrap();
}

/// The folders of a dataset. Cargo watches the dataset folder recursively, so
/// a new or changed circuit file reruns this script.
fn subfolders(dir: &Path) -> Vec<PathBuf> {
    println!("cargo:rerun-if-changed={}", dir.display());
    fs::read_dir(dir)
        .unwrap_or_else(|e| panic!("read {}: {e}", dir.display()))
        .filter_map(|e| e.ok())
        .map(|e| e.path())
        .filter(|p| p.is_dir())
        .collect()
}

/// `(case, target.rs)` for every DS-1000 case folder with a `target.rs`.
fn ds1000_cases(dataset: &Path) -> Vec<(String, PathBuf)> {
    subfolders(dataset)
        .into_iter()
        .filter_map(|dir| {
            let name = dir.file_name()?.to_str()?.to_string();
            let target = dir.join("target.rs");
            target.is_file().then_some((name, target))
        })
        .collect()
}

/// `(<program>__<function>, target.<function>.rs)` for every circuit of every
/// program folder.
fn shape_generic_cases(dataset: &Path) -> Vec<(String, PathBuf)> {
    let mut cases = Vec::new();
    for dir in subfolders(dataset) {
        let program = dir.file_name().and_then(|n| n.to_str()).expect("folder name").to_string();
        for file in fs::read_dir(&dir).expect("read program folder").filter_map(|e| e.ok()) {
            let file_name = file.file_name();
            let Some(function) = file_name
                .to_str()
                .and_then(|n| n.strip_prefix("target."))
                .and_then(|n| n.strip_suffix(".rs"))
            else {
                continue;
            };
            cases.push((format!("{program}__{function}"), file.path()));
        }
    }
    cases
}

/// External scaled sources replace original NPBench/Pythran cases, never union
/// with them: otherwise the same case ID could select CAP-16 constants.
fn npb_cases(datasets: &Path, source_root: Option<&Path>) -> Vec<(String, PathBuf)> {
    if let Some(root) = source_root {
        let root = root.canonicalize().expect("HALO2_HW_NPB_SOURCE_ROOT folder");
        return shape_generic_cases(&root);
    }
    SHAPE_GENERIC_DATASETS.iter()
        .flat_map(|dataset| shape_generic_cases(&datasets.join(dataset)))
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn scaled_sources_replace_originals_and_keep_function_ids() {
        let root = env::temp_dir().join(format!("halo2-hw-build-test-{}", std::process::id()));
        let original = root.join("datasets");
        let scaled = root.join("cap32");
        fs::create_dir_all(original.join("npbench/demo")).unwrap();
        fs::create_dir_all(original.join("pythran")).unwrap();
        fs::create_dir_all(scaled.join("demo")).unwrap();
        fs::write(original.join("npbench/demo/target.first.rs"), "original").unwrap();
        fs::write(scaled.join("demo/target.first.rs"), "scaled first").unwrap();
        fs::write(scaled.join("demo/target.second.rs"), "scaled second").unwrap();
        fs::write(scaled.join("demo/main.first.nr"), "ignored").unwrap();
        let base = npb_cases(&original, None);
        assert_eq!(base.len(), 1);
        assert_eq!(base[0].0, "demo__first");
        let mut candidates = npb_cases(&original, Some(&scaled));
        candidates.sort();
        assert_eq!(candidates.iter().map(|c| c.0.as_str()).collect::<Vec<_>>(),
                   ["demo__first", "demo__second"]);
        assert!(candidates.iter().all(|c| c.1.starts_with(scaled.canonicalize().unwrap())));
        assert_eq!(fs::read_to_string(&candidates[0].1).unwrap(), "scaled first");
        fs::remove_dir_all(root).unwrap();
    }
}
