from zinnia import *
import numpy as np

@zk_circuit
def kernel(TSTEPS: Integer, A: Float[Array, '3200'], B: Float[Array, '3200']):
    for t in range(1, TSTEPS):
        B[1:-1] = 0.33333 * (A[:-2] + A[1:-1] + A[2:])
        A[1:-1] = 0.33333 * (B[:-2] + B[1:-1] + B[2:])
