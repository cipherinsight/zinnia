from zinnia import *
import numpy as np

@zk_circuit
def kernel(TMAX: Integer, ex: Float[Array, '200 220'], ey: Float[Array, '200 220'], hz: Float[Array, '200 220'], _fict_: Float[Array, '20']):
    for t in range(TMAX):
        ey[0, :] = _fict_[t]
        ey[1:, :] -= 0.5 * (hz[1:, :] - hz[:-1, :])
        ex[:, 1:] -= 0.5 * (hz[:, 1:] - hz[:, :-1])
        hz[:-1, :-1] -= 0.7 * (ex[:-1, 1:] - ex[:-1, :-1] + ey[1:, :-1] - ey[:-1, :-1])
