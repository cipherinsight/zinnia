from zinnia import *
import numpy as np

@zk_circuit
def softmax(x: Float[Array, '16 16 128 128']):
    tmp_max = np.max(x, axis=-1, keepdims=True)
    tmp_out = np.exp(x - tmp_max)
    tmp_sum = np.sum(tmp_out, axis=-1, keepdims=True)
    return tmp_out / tmp_sum
